/**
 * Catálogo institucional B2B (sem preços nem compra online).
 *
 * As descrições apresentam a natureza e as aplicações correntes de cada família
 * de produto. Códigos, dimensões, classes, normas e outras especificações
 * técnicas só devem ser preenchidos a partir de fichas técnicas oficiais
 * (campo `specifications` / `datasheets`). Enquanto estiverem vazios, a
 * interface remete o visitante para o departamento comercial.
 */

type ProductInput = Omit<Product, 'specifications' | 'datasheets' | 'keywords'> &
  Partial<Pick<Product, 'specifications' | 'datasheets' | 'keywords'>>

function product(input: ProductInput): Product {
  return { specifications: [], datasheets: [], keywords: [], ...input }
}

